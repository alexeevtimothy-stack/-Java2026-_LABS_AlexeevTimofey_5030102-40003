/**
   *Класс Calculator предоставляет простейшие математические операции.
   *Этот комментарий javadoc описывает назначение всего класса.
   *@author Тимофей
   *@version 1.0
 */
public class Calculator {
    /**
      *Метод складывает два целых числа.
      *@param a первое число для сложения
      *@param b второе число для сложения
      *@return сумма чисел a и b
     */
    public int add(int a, int b) {
        return a + b;
    }
}

